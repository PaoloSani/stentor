"""Convert the frozen Sidon TorchScript graphs into plain (eager) PyTorch modules.

The released TorchScript files are frozen for CPU (hard-coded CPU `arange`s, float64
scalars), so they cannot run on Apple's MPS backend or in half precision. Their code,
however, only uses ~20 standard tensor ops, so we transcribe it mechanically into an
`nn.Module` and dump the frozen constants as an ordinary state dict.

Usage (from the repo root):
    .venv/bin/python tools/convert_torchscript.py

Outputs:
    speech_enhancer/_generated/{feature_extractor,decoder}.py   (generated code)
    sidon_weights/eager/{feature_extractor,decoder}.pt          (float32 state dicts)
"""

from __future__ import annotations

import re
import sys
import warnings
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "sidon_weights"
CODE_OUT = ROOT / "speech_enhancer" / "_generated"
WEIGHTS_OUT = SRC / "eager"

MODELS = {
    "feature_extractor": ("feature_extractor_cpu.pt", "FeatureExtractor"),
    "decoder": ("decoder_cpu.pt", "Decoder"),
}

HEADER = '''"""AUTO-GENERATED by tools/convert_torchscript.py from {src} -- do not edit."""
# fmt: off
# ruff: noqa
from typing import Dict

import torch
import torch.nn.functional as F
from torch import Tensor


def _rel_pos_scores(query: Tensor, table_and_index) -> Tensor:
    """== einsum("bhld,lrd->bhlr", query, table[index]) without building table[index]."""
    table, index = table_and_index  # table: (n_dist, d), index: (l, r)
    per_distance = torch.matmul(query, table.t())  # (b, h, l, n_dist)
    b, h, l, _ = per_distance.shape
    return torch.gather(per_distance, 3, index.expand(b, h, l, index.shape[1]))


class {cls}(torch.nn.Module):
    def __init__(self) -> None:
        super().__init__()
{buffers}

'''


def _replace_call(code: str, fn: str, rewrite) -> str:
    """Rewrite every `fn(arg0, rest...)` call, handling nested parentheses."""
    out, i = [], 0
    needle = fn + "("
    while True:
        j = code.find(needle, i)
        if j < 0:
            out.append(code[i:])
            return "".join(out)
        out.append(code[i:j])
        k, depth = j + len(needle), 1
        while depth:
            depth += {"(": 1, ")": -1}.get(code[k], 0)
            k += 1
        args = code[j + len(needle):k - 1]
        out.append(rewrite(_split_args(args)))
        i = k


def _split_args(s: str) -> list[str]:
    parts, depth, cur, in_str = [], 0, [], False
    for ch in s:
        if ch == '"':
            in_str = not in_str
        elif not in_str and ch in "([{":
            depth += 1
        elif not in_str and ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0 and not in_str:
            parts.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    parts.append("".join(cur).strip())
    return parts


def transcribe(code: str, consts: dict[str, object]) -> tuple[str, dict[str, torch.Tensor]]:
    buffers: dict[str, torch.Tensor] = {}

    def const(match: re.Match) -> str:
        name = match.group(1)
        value = consts[name]
        if isinstance(value, torch.Tensor) and value.numel() == 1 and value.dim() <= 1 and value.dtype in (torch.float64, torch.int64):
            return repr(value.item())  # scalar -> Python literal (no float64 tensor on MPS)
        if not isinstance(value, torch.Tensor):
            return repr(value)
        buffers[name] = value.float() if value.is_floating_point() else value
        return f"self.{name}"

    code = re.sub(r"CONSTANTS\.(c\d+)", const, code)
    # torch.to(x, 6) casts to float32: drop it so the module follows the input dtype (fp16 on MPS).
    code = _replace_call(code, "torch.to", lambda a: a[0] if a[1] == "6" else f"{a[0]}.to({a[1]})")
    code = _replace_call(code, "torch.view", lambda a: f"{a[0]}.view({a[1]})")
    code = _replace_call(code, "torch.size", lambda a: f"{a[0]}.size({', '.join(a[1:])})")
    # Ops exposed by TorchScript under `torch.` but only available in Python as `F.` (silu, glu, pad...).
    for name in sorted(set(re.findall(r"torch\.(\w+)\(", code))):
        if not hasattr(torch, name):
            if not hasattr(torch.nn.functional, name):
                raise RuntimeError(f"Unknown op torch.{name}")
            code = code.replace(f"torch.{name}(", f"F.{name}(")
    code = code.replace("dtype=4", "dtype=torch.long")
    code = re.sub(r'device=torch\.device\("cpu"\)', "device=__DEVICE__", code)

    # Relative-position attention: `einsum("bhld,lrd->bhlr", q, embedding(W, idx))` materialises an
    # (l, r, d) tensor (and a huge broadcast on MPS). Distances are clamped, so W has only a few
    # rows: compute q @ W^T once and gather instead -- same result, a fraction of the memory.
    code = _replace_call(code, "torch.embedding", lambda a: f"({a[0]}, {a[1]})")
    code = _replace_call(
        code,
        "torch.einsum",
        lambda a: f"_rel_pos_scores(*{a[1]})" if a[0] == '"bhld,lrd->bhlr"' else f"torch.einsum({', '.join(a)})",
    )

    # Snake activations wrap themselves in `reshape(x, [s[0], s[1], -1])` ... `reshape(y, s)` with
    # `s = x.size()`; on the decoder's (B, C, T) tensors both are identities, and their dynamic
    # shape arithmetic breaks tracing for Core ML. Drop them.
    code = re.sub(r"torch\.reshape\((\w+), \[(\w+)\[0\], \2\[1\], -1\]\)", r"\1", code)
    code = re.sub(r"torch\.reshape\((\w+), (shape\d*)\)", r"\1", code)
    code = re.sub(r"\n\s*shape\d* = \w+\.size\(\)", "", code)

    # The first argument of forward() provides the runtime device.
    first_arg = re.search(r"def forward\(self,\s*(\w+)", code).group(1)
    code = code.replace("__DEVICE__", f"{first_arg}.device")

    leftovers = sorted(set(re.findall(r"CONSTANTS|torch\.device\(|torch\.to\(|dtype=7", code)))
    if leftovers:
        raise RuntimeError(f"Unhandled constructs after transcription: {leftovers}")
    return code, buffers


def convert(key: str) -> None:
    src_name, cls = MODELS[key]
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        module = torch.jit.load(str(SRC / src_name), map_location="cpu")
    code, consts = module.code_with_constants
    body, buffers = transcribe(code, consts.const_mapping)

    # Register every weight as a buffer with its real shape (filled by load_state_dict).
    buf_lines = "\n".join(
        f"        self.register_buffer({n!r}, torch.empty({list(t.shape)}, dtype={t.dtype}))" for n, t in buffers.items()
    )
    body = "\n".join(("    " + line) if line else line for line in body.strip("\n").split("\n"))
    source = HEADER.format(src=src_name, cls=cls, buffers=buf_lines) + body + "\n"

    CODE_OUT.mkdir(parents=True, exist_ok=True)
    WEIGHTS_OUT.mkdir(parents=True, exist_ok=True)
    (CODE_OUT / f"{key}.py").write_text(source)
    torch.save(buffers, WEIGHTS_OUT / f"{key}.pt")
    n = sum(t.numel() for t in buffers.values())
    print(f"{key}: {len(buffers)} tensors, {n / 1e6:.1f}M params -> {CODE_OUT / (key + '.py')}")


def main() -> None:
    for key in sys.argv[1:] or MODELS:
        convert(key)
    (CODE_OUT / "__init__.py").write_text('"""Eager Sidon modules generated from the TorchScript release."""\n')


if __name__ == "__main__":
    main()
